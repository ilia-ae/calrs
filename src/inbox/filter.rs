//! Mail that is not a guest writing: autoreplies, bounces and receipts,
//! lists, calendar answers to our invites, and our own mail coming back.
//! Such a message is marked handled (seen or moved) and counted by reason;
//! nothing is stored and nobody is told.

use super::mime::Inbound;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Drop {
    /// Auto-Submitted, X-Autoreply and the like (out of office included).
    AutoReply,
    /// Precedence bulk, junk, list or auto_reply.
    Bulk,
    /// List-Id or List-Unsubscribe.
    List,
    /// A delivery or read report (`multipart/report`).
    Report,
    /// From a mailer daemon or postmaster, or an empty return path.
    Daemon,
    /// An iTIP REPLY, COUNTER or REFRESH (the guest's calendar answering the
    /// invite whose ORGANIZER is the system).
    Calendar,
    /// Our own mail.
    Loop,
}

impl Drop {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Drop::AutoReply => "autoreply",
            Drop::Bulk => "bulk",
            Drop::List => "list",
            Drop::Report => "report",
            Drop::Daemon => "daemon",
            Drop::Calendar => "calendar",
            Drop::Loop => "loop",
        }
    }
}

/// Our own addresses and domain.
#[derive(Debug, Clone, Default)]
pub(crate) struct Ours {
    /// Local parts at `domain` (the mailbox's, plus-tagged forms included).
    locals: Vec<String>,
    /// Other own addresses (the SMTP From).
    addresses: Vec<String>,
    domain: String,
}

impl Ours {
    pub(crate) fn new(inbox_address: &str, smtp_from: Option<&str>) -> Self {
        let inbox = inbox_address.trim().to_ascii_lowercase();
        let (local, domain) = inbox.split_once('@').unwrap_or((&inbox, ""));
        Self {
            locals: vec![local.to_string()],
            addresses: smtp_from
                .map(|a| a.trim().to_ascii_lowercase())
                .into_iter()
                .collect(),
            domain: domain.to_string(),
        }
    }

    pub(crate) fn domain(&self) -> &str {
        &self.domain
    }

    /// Whether `address` is one of ours: the mailbox (with any `+tag`) or
    /// the SMTP From.
    pub(crate) fn is_ours(&self, address: &str) -> bool {
        let address = address.to_ascii_lowercase();
        if self.addresses.contains(&address) {
            return true;
        }
        let Some((local, domain)) = address.rsplit_once('@') else {
            return false;
        };
        let base = local.split('+').next().unwrap_or(local);
        domain == self.domain && self.locals.iter().any(|l| l == base)
    }
}

/// Why `m` is not a guest writing, if it is not.
pub(crate) fn check(m: &Inbound, ours: &Ours) -> Option<Drop> {
    if m.header("x-calrs-origin").is_some() {
        return Some(Drop::Loop);
    }
    if m.from.as_deref().is_some_and(|f| ours.is_ours(f)) {
        return Some(Drop::Loop);
    }
    if let Some(id) = &m.message_id {
        let id = id.to_ascii_lowercase();
        if id.starts_with(super::reply::MESSAGE_ID_PREFIX)
            && id.ends_with(&format!("@{}", ours.domain()))
        {
            return Some(Drop::Loop);
        }
    }
    if m.header("auto-submitted")
        .is_some_and(|v| !v.trim().eq_ignore_ascii_case("no"))
        || m.header("x-autoreply").is_some()
        || m.header("x-autorespond").is_some()
        || m.header("x-autogenerated").is_some()
    {
        return Some(Drop::AutoReply);
    }
    if let Some(p) = m.header("precedence") {
        let p = p.trim().to_ascii_lowercase();
        if matches!(p.as_str(), "bulk" | "junk" | "list" | "auto_reply") {
            return Some(Drop::Bulk);
        }
    }
    if m.header("list-id").is_some() || m.header("list-unsubscribe").is_some() {
        return Some(Drop::List);
    }
    if m.report {
        return Some(Drop::Report);
    }
    let daemon = |a: &str| {
        let local = a.split('@').next().unwrap_or("");
        local.eq_ignore_ascii_case("mailer-daemon") || local.eq_ignore_ascii_case("postmaster")
    };
    if m.from.as_deref().is_none_or(|f| f.is_empty() || daemon(f))
        || m.header("return-path").is_some_and(|r| r.trim() == "<>")
    {
        return Some(Drop::Daemon);
    }
    if m.calendar_method
        .as_deref()
        .is_some_and(|method| matches!(method, "REPLY" | "COUNTER" | "REFRESH"))
    {
        return Some(Drop::Calendar);
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ours() -> Ours {
        Ours::new("booking@ilia.ae", Some("noreply@ilia.ae"))
    }

    fn guest() -> Inbound {
        Inbound {
            message_id: Some("abc@gmail.com".into()),
            from: Some("guest@gmail.com".into()),
            ..Default::default()
        }
    }

    fn with(name: &str, value: &str) -> Inbound {
        let mut m = guest();
        m.headers.push((name.into(), value.into()));
        m
    }

    #[test]
    fn a_guest_passes() {
        assert_eq!(check(&guest(), &ours()), None);
        assert_eq!(check(&with("auto-submitted", "no"), &ours()), None);
    }

    #[test]
    fn automatic_mail_is_dropped_by_reason() {
        for (m, why) in [
            (with("auto-submitted", "auto-replied"), Drop::AutoReply),
            // Kerio's out-of-office reply.
            (
                with("auto-submitted", "auto-replied (vacation)"),
                Drop::AutoReply,
            ),
            (with("x-autoreply", "yes"), Drop::AutoReply),
            (with("precedence", "Bulk"), Drop::Bulk),
            (with("precedence", "auto_reply"), Drop::Bulk),
            (with("list-id", "<news.example>"), Drop::List),
            (with("return-path", "<>"), Drop::Daemon),
            (with("x-calrs-origin", "1"), Drop::Loop),
        ] {
            assert_eq!(check(&m, &ours()), Some(why), "{m:?}");
        }
        let mut dsn = guest();
        dsn.report = true;
        assert_eq!(check(&dsn, &ours()), Some(Drop::Report));
        let mut daemon = guest();
        daemon.from = Some("MAILER-DAEMON@mx.example".into());
        assert_eq!(check(&daemon, &ours()), Some(Drop::Daemon));
        let mut rsvp = guest();
        rsvp.calendar_method = Some("REPLY".into());
        assert_eq!(check(&rsvp, &ours()), Some(Drop::Calendar));
    }

    #[test]
    fn our_own_mail_is_a_loop() {
        for from in ["booking@ilia.ae", "Booking+x@ilia.ae", "noreply@ilia.ae"] {
            let mut m = guest();
            m.from = Some(from.into());
            assert_eq!(check(&m, &ours()), Some(Drop::Loop), "{from}");
        }
        let mut m = guest();
        m.message_id = Some("calrs.abcdefghijklmnop.00ff@ilia.ae".into());
        assert_eq!(check(&m, &ours()), Some(Drop::Loop));
        // Another domain's "calrs." id is not ours.
        m.message_id = Some("calrs.x@other.example".into());
        assert_eq!(check(&m, &ours()), None);
    }
}

//! A fetched message, reduced to what the inbox decides on. Parsing is
//! mail-parser's (charsets, quoted-printable, base64, RFC 2047 words); the
//! text is the first `text/plain` body, else the HTML body converted to
//! text by mail-parser. HTML itself is never kept.

use mail_parser::{MessageParser, MimeHeaders};

/// What the inbox reads of one message. Everything here is untrusted.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub(crate) struct Inbound {
    /// Message-ID without the angle brackets.
    pub(crate) message_id: Option<String>,
    /// The From address, lowercased.
    pub(crate) from: Option<String>,
    /// Every recipient address we may have been reached at, lowercased:
    /// To, Cc, Delivered-To, X-Original-To, Envelope-To.
    pub(crate) recipients: Vec<String>,
    /// In-Reply-To and References, as written.
    pub(crate) references: String,
    pub(crate) subject: String,
    /// Headers the filter reads, name lowercased, value trimmed.
    pub(crate) headers: Vec<(String, String)>,
    /// `multipart/report` (a DSN or MDN) at the top.
    pub(crate) report: bool,
    /// A `text/calendar` part's METHOD (`REPLY`, `COUNTER`, …), uppercased.
    pub(crate) calendar_method: Option<String>,
    /// The body as text, before cleaning.
    pub(crate) text: Option<String>,
}

impl Inbound {
    /// The first value of a header (`name` lowercase).
    pub(crate) fn header(&self, name: &str) -> Option<&str> {
        self.headers
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, v)| v.as_str())
    }
}

/// Headers kept for the filter and the matcher.
const KEPT: &[&str] = &[
    "auto-submitted",
    "precedence",
    "x-autoreply",
    "x-autorespond",
    "x-autogenerated",
    "x-auto-response-suppress",
    "list-id",
    "list-unsubscribe",
    "return-path",
    "x-calrs-origin",
    "delivered-to",
    "x-original-to",
    "envelope-to",
];

/// Addresses in a raw header value: `<a@b>` forms, else bare `a@b` words.
pub(crate) fn addresses_in(value: &str) -> Vec<String> {
    let mut out = Vec::new();
    for part in value.split(',') {
        let addr = match (part.find('<'), part.rfind('>')) {
            (Some(a), Some(b)) if a < b => part[a + 1..b].trim(),
            _ => part
                .split_whitespace()
                .find(|w| w.contains('@'))
                .unwrap_or("")
                .trim_matches(|c: char| c == '"' || c == '\'' || c == ';'),
        };
        if addr.contains('@') && addr.len() <= 254 {
            out.push(addr.to_ascii_lowercase());
        }
    }
    out
}

/// Parse a raw message. `None`: not a message mail-parser can read.
pub(crate) fn parse(raw: &[u8]) -> Option<Inbound> {
    let message = MessageParser::default().parse(raw)?;
    let mut inbound = Inbound {
        message_id: message.message_id().map(|id| id.trim().to_string()),
        from: message
            .from()
            .and_then(|f| f.first())
            .and_then(|a| a.address())
            .map(|a| a.trim().to_ascii_lowercase()),
        subject: message.subject().unwrap_or_default().to_string(),
        ..Default::default()
    };
    for header in message.headers() {
        let name = header.name().to_ascii_lowercase();
        if KEPT.contains(&name.as_str()) {
            let value = message
                .raw_message()
                .get(header.offset_start as usize..header.offset_end as usize)
                .map(|v| String::from_utf8_lossy(v).trim().to_string())
                .unwrap_or_default();
            inbound.headers.push((name, value));
        }
    }
    for addr in message.to().into_iter().chain(message.cc()) {
        for a in addr.iter() {
            if let Some(a) = a.address() {
                inbound.recipients.push(a.trim().to_ascii_lowercase());
            }
        }
    }
    for name in ["delivered-to", "x-original-to", "envelope-to"] {
        let values: Vec<String> = inbound
            .headers
            .iter()
            .filter(|(n, _)| n == name)
            .map(|(_, v)| v.clone())
            .collect();
        for v in values {
            inbound.recipients.extend(addresses_in(&v));
        }
    }
    let mut refs = Vec::new();
    for value in [message.in_reply_to(), message.references()] {
        if let Some(text) = value.as_text() {
            refs.push(text.to_string());
        }
        if let Some(list) = value.as_text_list() {
            refs.extend(list.iter().map(|s| s.to_string()));
        }
    }
    inbound.references = refs.join(" ");
    inbound.report = message.root_part().content_type().is_some_and(|ct| {
        ct.c_type.eq_ignore_ascii_case("multipart")
            && ct
                .c_subtype
                .as_ref()
                .is_some_and(|s| s.eq_ignore_ascii_case("report"))
    });
    for part in &message.parts {
        if !part.is_content_type("text", "calendar") {
            continue;
        }
        let method = part
            .content_type()
            .and_then(|ct| ct.attribute("method"))
            .map(str::to_string)
            .or_else(|| {
                let text = String::from_utf8_lossy(part.contents()).into_owned();
                text.lines().find_map(|l| {
                    l.trim()
                        .strip_prefix("METHOD:")
                        .map(|m| m.trim().to_string())
                })
            });
        if let Some(m) = method {
            inbound.calendar_method = Some(m.to_ascii_uppercase());
            break;
        }
    }
    inbound.text = message.body_text(0).map(|t| t.into_owned());
    Some(inbound)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn addresses_are_read_from_raw_headers() {
        assert_eq!(
            addresses_in(" \"Booking\" <Booking+ABC@Ilia.ae>, x@y.z"),
            vec!["booking+abc@ilia.ae", "x@y.z"]
        );
        assert!(addresses_in("nobody").is_empty());
    }

    #[test]
    fn a_windows_1251_reply_is_decoded() {
        let body: Vec<u8> = [
            &b"From: =?windows-1251?B?yOLg7Q==?= <ivan@example.ru>\r\nTo: booking@ilia.ae\r\n\
Subject: Re: test\r\nMessage-ID: <m1@example.ru>\r\nIn-Reply-To: <calrs.abcdefghijklmnop.0011@ilia.ae>\r\n\
Content-Type: text/plain; charset=windows-1251\r\nContent-Transfer-Encoding: 8bit\r\n\r\n"[..],
            // «Добрый день» in windows-1251.
            &[0xC4, 0xEE, 0xE1, 0xF0, 0xFB, 0xE9, 0x20, 0xE4, 0xE5, 0xED, 0xFC, b'\r', b'\n'],
        ]
        .concat();
        let m = parse(&body).unwrap();
        assert_eq!(m.from.as_deref(), Some("ivan@example.ru"));
        assert_eq!(m.message_id.as_deref(), Some("m1@example.ru"));
        assert!(m.references.contains("calrs.abcdefghijklmnop.0011@ilia.ae"));
        assert_eq!(m.text.as_deref().map(str::trim), Some("Добрый день"));
        assert_eq!(m.recipients, vec!["booking@ilia.ae"]);
    }

    #[test]
    fn html_only_mail_becomes_text_without_markup() {
        let raw = b"From: a@b.example\r\nTo: booking@ilia.ae\r\nSubject: hi\r\n\
Content-Type: text/html; charset=utf-8\r\n\r\n<html><head><script>alert(1)</script></head>\
<body><p>Hello <b>there</b></p><img src=\"https://track.example/x.gif\"></body></html>\r\n";
        let m = parse(raw).unwrap();
        let text = m.text.unwrap();
        assert!(text.contains("Hello") && text.contains("there"), "{text}");
        assert!(
            !text.contains('<') && !text.contains("track.example"),
            "{text}"
        );
    }

    #[test]
    fn reports_and_calendar_answers_are_flagged() {
        let dsn =
            b"From: MAILER-DAEMON@mx.example\r\nTo: booking@ilia.ae\r\nSubject: Undelivered\r\n\
Content-Type: multipart/report; report-type=delivery-status; boundary=\"b\"\r\n\r\n\
--b\r\nContent-Type: text/plain\r\n\r\nfailed\r\n--b--\r\n";
        assert!(parse(dsn).unwrap().report);
        let rsvp = b"From: g@x.example\r\nTo: booking@ilia.ae\r\nSubject: Accepted\r\n\
Content-Type: multipart/mixed; boundary=\"b\"\r\n\r\n--b\r\nContent-Type: text/plain\r\n\r\nok\r\n\
--b\r\nContent-Type: text/calendar; charset=utf-8\r\n\r\nBEGIN:VCALENDAR\r\nMETHOD:REPLY\r\nEND:VCALENDAR\r\n--b--\r\n";
        assert_eq!(
            parse(rsvp).unwrap().calendar_method.as_deref(),
            Some("REPLY")
        );
    }
}
